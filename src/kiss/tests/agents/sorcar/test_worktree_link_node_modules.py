"""End-to-end tests for ``GitWorktreeOps.link_node_modules``.

A worktree checks out tracked files only, so the main checkout's
git-ignored ``node_modules`` directories are missing and every JS test,
``npm run compile`` and extension lint fails until the agent reinstalls
or links them by hand (seven ``npm install`` runs in worktrees in one
day of ``sorcar.db``).  The helper links them at worktree setup and
keeps the link out of git through ``info/exclude``.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from pathlib import Path

import pytest

import kiss.agents.sorcar.persistence as th
from kiss.agents.sorcar.git_worktree import GitWorktreeOps
from kiss.agents.sorcar.worktree_sorcar_agent import WorktreeSorcarAgent
from kiss.tests.conftest import IS_WINDOWS

pytestmark = pytest.mark.skipif(IS_WINDOWS, reason="symlinks need privileges on Windows")


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True, check=True,
    ).stdout


def _make_repo(path: Path, *, ignored_node_modules: bool = True) -> Path:
    """Create a repo with ``pkg/`` tracked and an ignored ``pkg/node_modules``."""
    path.mkdir(parents=True)
    subprocess.run(["git", "init", "-b", "main", str(path)], capture_output=True, check=True)
    _git(path, "config", "user.email", "t@t.com")
    _git(path, "config", "user.name", "T")
    (path / ".gitignore").write_text("node_modules/\n")
    (path / "pkg").mkdir()
    (path / "pkg" / "index.js").write_text("module.exports = 1;\n")
    _git(path, "add", ".")
    _git(path, "commit", "-m", "initial")
    if ignored_node_modules:
        (path / "pkg" / "node_modules" / "dep").mkdir(parents=True)
        (path / "pkg" / "node_modules" / "dep" / "index.js").write_text("module.exports = 2;\n")
    return path


def _make_worktree(repo: Path, name: str) -> Path:
    wt_dir = repo / ".kiss-worktrees" / name
    assert GitWorktreeOps.create(repo, f"kiss/wt-{name}", wt_dir)
    return wt_dir


def _exclude_lines(repo: Path) -> list[str]:
    common = Path(_git(repo, "rev-parse", "--git-common-dir").strip())
    if not common.is_absolute():
        common = repo / common
    exclude = common / "info" / "exclude"
    return exclude.read_text().splitlines() if exclude.exists() else []


class TestLinkNodeModules:
    def setup_method(self) -> None:
        self.tmp = Path(tempfile.mkdtemp())

    def teardown_method(self) -> None:
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_links_ignored_dir_and_keeps_git_clean(self) -> None:
        repo = _make_repo(self.tmp / "repo")
        wt_dir = _make_worktree(repo, "a")
        assert not (wt_dir / "pkg" / "node_modules").exists()

        linked = GitWorktreeOps.link_node_modules(repo, wt_dir)

        assert linked == [Path("pkg/node_modules")]
        link = wt_dir / "pkg" / "node_modules"
        assert link.is_symlink()
        assert Path(os.readlink(link)) == (repo / "pkg" / "node_modules").resolve()
        assert (link / "dep" / "index.js").read_text() == "module.exports = 2;\n"
        # ``node_modules/`` in .gitignore matches directories only; the bare
        # pattern in info/exclude keeps the symlink out of ``git add -A``.
        assert "node_modules" in _exclude_lines(repo)
        assert _git(wt_dir, "status", "--porcelain") == ""
        GitWorktreeOps.stage_all(wt_dir)
        assert _git(wt_dir, "diff", "--cached", "--name-only") == ""

    def test_second_call_is_a_no_op(self) -> None:
        repo = _make_repo(self.tmp / "repo")
        wt_dir = _make_worktree(repo, "a")
        assert GitWorktreeOps.link_node_modules(repo, wt_dir) == [Path("pkg/node_modules")]
        assert GitWorktreeOps.link_node_modules(repo, wt_dir) == []
        assert _exclude_lines(repo).count("node_modules") == 1

    def test_existing_directory_in_worktree_is_kept(self) -> None:
        repo = _make_repo(self.tmp / "repo")
        wt_dir = _make_worktree(repo, "a")
        own = wt_dir / "pkg" / "node_modules"
        own.mkdir()
        (own / "mine.txt").write_text("keep\n")
        assert GitWorktreeOps.link_node_modules(repo, wt_dir) == []
        assert not own.is_symlink()
        assert (own / "mine.txt").read_text() == "keep\n"

    def test_no_ignored_node_modules_links_nothing(self) -> None:
        repo = _make_repo(self.tmp / "repo", ignored_node_modules=False)
        wt_dir = _make_worktree(repo, "a")
        assert GitWorktreeOps.link_node_modules(repo, wt_dir) == []
        assert "node_modules" not in _exclude_lines(repo)

    def test_node_modules_under_untracked_dir_is_skipped(self) -> None:
        """No parent directory in the worktree means nothing to link into."""
        repo = _make_repo(self.tmp / "repo", ignored_node_modules=False)
        (repo / "scratch" / "node_modules").mkdir(parents=True)
        (repo / ".git" / "info").mkdir(exist_ok=True)
        with open(repo / ".git" / "info" / "exclude", "a") as f:
            f.write("scratch/\n")
        wt_dir = _make_worktree(repo, "a")
        assert GitWorktreeOps.link_node_modules(repo, wt_dir) == []
        assert not (wt_dir / "scratch").exists()

    def test_other_ignored_dirs_are_not_linked(self) -> None:
        """Only ``node_modules`` is linked; build output stays worktree-local."""
        repo = _make_repo(self.tmp / "repo")
        (repo / ".gitignore").write_text("node_modules/\nout/\n")
        _git(repo, "commit", "-am", "ignore out")
        (repo / "pkg" / "out").mkdir()
        (repo / "pkg" / "out" / "bundle.js").write_text("built\n")
        wt_dir = _make_worktree(repo, "a")
        assert GitWorktreeOps.link_node_modules(repo, wt_dir) == [Path("pkg/node_modules")]
        assert not (wt_dir / "pkg" / "out").exists()

    @pytest.mark.skipif(os.geteuid() == 0, reason="root ignores file permissions")
    def test_unwritable_exclude_creates_no_link(self) -> None:
        """When info/exclude cannot be written, no committable link is left."""
        repo = _make_repo(self.tmp / "repo")
        wt_dir = _make_worktree(repo, "a")
        exclude = repo / ".git" / "info" / "exclude"
        exclude.parent.mkdir(exist_ok=True)
        exclude.touch()
        exclude.chmod(0o444)
        try:
            with pytest.raises(OSError):
                GitWorktreeOps.link_node_modules(repo, wt_dir)
        finally:
            exclude.chmod(0o644)
        assert not (wt_dir / "pkg" / "node_modules").is_symlink()
        GitWorktreeOps.stage_all(wt_dir)
        assert _git(wt_dir, "diff", "--cached", "--name-only") == ""

    def test_non_git_directory_links_nothing(self) -> None:
        plain = self.tmp / "plain"
        (plain / "pkg" / "node_modules").mkdir(parents=True)
        wt_dir = self.tmp / "wt"
        (wt_dir / "pkg").mkdir(parents=True)
        assert GitWorktreeOps.link_node_modules(plain, wt_dir) == []
        assert not (wt_dir / "pkg" / "node_modules").exists()


class TestWorktreeAgentSetupLinks:
    """``_try_setup_worktree`` links the directories for a real task worktree."""

    def setup_method(self) -> None:
        self.tmp = Path(tempfile.mkdtemp())
        self._saved = (th._DB_PATH, th._db_conn, th._KISS_DIR)
        kiss_dir = self.tmp / ".kiss"
        kiss_dir.mkdir()
        th._KISS_DIR = kiss_dir
        th._DB_PATH = kiss_dir / "sorcar.db"
        th._db_conn = None

    def teardown_method(self) -> None:
        if th._db_conn is not None:
            th._db_conn.close()
            th._db_conn = None
        (th._DB_PATH, th._db_conn, th._KISS_DIR) = self._saved
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_task_worktree_sees_main_node_modules(self) -> None:
        repo = _make_repo(self.tmp / "repo")
        agent = WorktreeSorcarAgent("wt_agent")
        agent._chat_id = "tab"
        wt_work = agent._try_setup_worktree(repo, str(repo))
        assert wt_work is not None
        wt = agent._wt
        assert wt is not None
        try:
            link = wt.wt_dir / "pkg" / "node_modules"
            assert link.is_symlink()
            assert (link / "dep" / "index.js").exists()
            assert _git(wt.wt_dir, "status", "--porcelain") == ""
        finally:
            GitWorktreeOps.remove(repo, wt.wt_dir)
        # Removing the worktree deletes the link, never the linked directory.
        assert (repo / "pkg" / "node_modules" / "dep" / "index.js").exists()

    @pytest.mark.skipif(os.geteuid() == 0, reason="root ignores file permissions")
    def test_setup_survives_unwritable_exclude(self) -> None:
        """A failed link is logged; the task still gets its worktree, unlinked."""
        repo = _make_repo(self.tmp / "repo")
        exclude = repo / ".git" / "info" / "exclude"
        exclude.parent.mkdir(exist_ok=True)
        exclude.touch()
        exclude.chmod(0o444)
        agent = WorktreeSorcarAgent("wt_agent")
        agent._chat_id = "tab"
        try:
            wt_work = agent._try_setup_worktree(repo, str(repo))
        finally:
            exclude.chmod(0o644)
        assert wt_work is not None
        wt = agent._wt
        assert wt is not None
        try:
            assert not (wt.wt_dir / "pkg" / "node_modules").exists()
            assert _git(wt.wt_dir, "status", "--porcelain") == ""
        finally:
            GitWorktreeOps.remove(repo, wt.wt_dir)
