"""End-to-end tests for what a fresh worktree shares with the main checkout.

``GitWorktreeOps.link_node_modules``: a worktree checks out tracked
files only, so the main checkout's
git-ignored ``node_modules`` directories are missing and every JS test,
``npm run compile`` and extension lint fails until the agent reinstalls
or links them by hand (seven ``npm install`` runs in worktrees in one
day of ``history.db``).  The helper links them at worktree setup and
keeps the link out of git through ``info/exclude``.

``GitWorktreeOps.block_own_environment``: a worktree shares the main
checkout's Python environment, and a ``.venv`` file keeps uv from
building it a second one (``TestBlockOwnEnvironment`` runs the real
``uv`` against it, directly, inside ``bash -c`` and from a script).
"""

from __future__ import annotations

